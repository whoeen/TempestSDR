function metrics = diagnoseIq(iq)
%DIAGNOSEIQ Quantization, DC and impropriety diagnostics in ADC counts.
arguments
    iq (:,1) {mustBeNumeric}
end
x = double(iq);
inphase = real(x); quadrature = imag(x);
centered = x-mean(x);
varianceI = var(inphase,1); varianceQ = var(quadrature,1);
totalPower = mean(abs(x).^2);
centeredPower = mean(abs(centered).^2);
covarianceIQ = mean((inphase-mean(inphase)).*(quadrature-mean(quadrature)));
metrics = struct('sample_count',numel(x),'finite_fraction',mean(isfinite(x)), ...
    'mean_i_counts',mean(inphase),'mean_q_counts',mean(quadrature), ...
    'median_i_counts',median(inphase),'median_q_counts',median(quadrature), ...
    'mad_i_counts',median(abs(inphase-median(inphase))), ...
    'mad_q_counts',median(abs(quadrature-median(quadrature))), ...
    'rms_complex_counts',sqrt(totalPower), ...
    'dc_power_fraction',abs(mean(x))^2/max(totalPower,eps), ...
    'clip_i_fraction',mean(inphase>=32767 | inphase<=-32768), ...
    'clip_q_fraction',mean(quadrature>=32767 | quadrature<=-32768), ...
    'zero_pair_fraction',mean(inphase==0 & quadrature==0), ...
    'iq_std_ratio',sqrt(varianceI/max(varianceQ,eps)), ...
    'iq_correlation',covarianceIQ/sqrt(max(varianceI*varianceQ,eps)), ...
    'impropriety_abs',abs(mean(centered.^2))/max(centeredPower,eps), ...
    'peak_over_rms',max(abs(x))/max(sqrt(totalPower),eps), ...
    'interpretation','IQ correlation/impropriety can be modulation, not solely receiver imbalance; no automatic correction.');
end
