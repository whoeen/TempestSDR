function [basis, meta] = dsiTimeMixCafBasis27(model, emissionIndex, coordinates, mix)
%DSITIMEMIXCAFBASIS27 Match a frozen complex-IQ time mixer before forming CAF.
%   Each column q of MIX.weights defines
%       y_q(t) = sum_j weights(j,q)*z(t+timeOffsetsSeconds(j)).
%   Multiple columns mean SUM OF BRANCH CAFs, with NO cross terms between q.
%   This permits PCA mode ensembles while retaining a common physical lane h.
%   Positive time offsets represent a frame comb; causal FIR offsets are
%   negative. Weights include every frozen common phase factor.
%
%   COORDINATES: fsHz, fcHz, lagSamples, harmonicOrders, delayPhase.
%   Optional MIX.periodicRfGridInvariant=true asserts offsets*f0 are integers
%   and replaces numerical response roundoff by the exact common-scalar
%   response for the periodic RF codebook. This is a MODEL property, not
%   proof of real signal stationarity, mode identity, or physical decoding.
%   This function cannot represent a spatial projector, data-dependent phase
%   correction, or time-varying resampling solely as a fixed time mixer.

arguments
    model (1,1) struct
    emissionIndex (1,1) {mustBeNumeric, mustBeReal, mustBeInteger, mustBePositive}
    coordinates (1,1) struct
    mix (1,1) struct
end
assert(all(isfield(coordinates,["fsHz","fcHz","lagSamples", ...
    "harmonicOrders","delayPhase"])),"Missing CAF coordinates.");
assert(all(isfield(mix,["weights","timeOffsetsSeconds"])), ...
    "Time mixer needs weights and explicit time offsets.");
validateattributes(mix.weights,{'numeric'},{'2d','nonempty','finite'});
validateattributes(mix.timeOffsetsSeconds,{'numeric'}, ...
    {'vector','nonempty','real','finite'});
weights=double(mix.weights);
offsets=double(mix.timeOffsetsSeconds(:));
if isvector(weights),weights=weights(:);end
assert(size(weights,1)==numel(offsets),"Time-mixer lengths differ.");
assert(any(abs(weights)>0,"all"),"Time mixer is identically zero.");
validateattributes(coordinates.delayPhase,{'numeric'},{'scalar','real','finite'});
frequencyBbHz=double(model.harmonics(:))*double(model.f0Hz)- ...
    double(coordinates.fcHz);
response=exp((2i*pi*frequencyBbHz)*offsets.')*weights;
normalizer=max(sum(abs(weights),1),realmin);
invarianceError=max(abs(response-response(1,:)),[],1)./normalizer;
periodicInvariant=isfield(mix,"periodicRfGridInvariant") && ...
    logical(mix.periodicRfGridInvariant);
if periodicInvariant
    cycleOffsets=offsets*double(model.f0Hz);
    assert(max(abs(cycleOffsets-round(cycleOffsets)))<1e-8, ...
        "Requested scalar invariance but time offsets are not RF periods.");
    assert(max(invarianceError)<1e-6, ...
        "Numeric frame-comb scalar invariance check failed.");
    commonResponse=sum(weights.* ...
        exp(-2i*pi*double(coordinates.fcHz)*offsets),1);
    response=repmat(commonResponse,numel(frequencyBbHz),1);
end
numberBranches=size(weights,2);
basis=complex(zeros(numel(coordinates.harmonicOrders)* ...
    numel(coordinates.lagSamples),9));
for branch=1:numberBranches
    filteredModel=model;
    filteredModel.coefficients{emissionIndex}= ...
        model.coefficients{emissionIndex}.*response(:,branch);
    [part,baseMeta]=dsiCafBasis27(filteredModel,emissionIndex, ...
        coordinates.fsHz,coordinates.fcHz,coordinates.lagSamples(:), ...
        coordinates.harmonicOrders(:));
    basis=basis+part;
end
orderVector=repmat(coordinates.harmonicOrders(:), ...
    numel(coordinates.lagSamples),1);
basis=basis.*exp(-2i*pi*orderVector*coordinates.delayPhase);
meta=struct("operator","y_q(t)=sum_j weights(j,q)*z(t+offset(j))", ...
    "branch_combination","Sum of branch CAFs, no cross terms", ...
    "number_branches",numberBranches, ...
    "forward_operator_matched",true, ...
    "weights_real",real(weights),"weights_imag",imag(weights), ...
    "time_offsets_seconds",offsets, ...
    "frequency_bb_hz",frequencyBbHz, ...
    "response_real",real(response),"response_imag",imag(response), ...
    "response_common_scalar_relative_error", ...
        max(invarianceError), ...
    "response_common_scalar_branch_error",invarianceError, ...
    "periodic_rf_scalar_invariance_asserted",periodicInvariant, ...
    "sum_branch_scalar_power",sum(abs(response(1,:)).^2), ...
    "max_response_magnitude",max(abs(response),[],"all"), ...
    "delay_phase",coordinates.delayPhase, ...
    "base_coordinate_meta",rmfield(baseMeta,"pairMatrices"), ...
    "physical_channel_identified",false);
end
