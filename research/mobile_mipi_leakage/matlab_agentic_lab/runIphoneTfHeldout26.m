function manifest = runIphoneTfHeldout26
%RUNIPHONETFHELDOUT26 Heldout frame72 TF evidence after accumulated timing drift.
% Before/after: saved singleTest columns1/4, same131072-point canonical excerpt
% beginning at floor(2^21*1000/1881), in frame72 (zero based). Grid Fs and
% native ADC Fs are loaded from the completed timing model, never inferred.
% Native: contiguous131072 IQ samples beginning at floor(raw query coordinate),
% read with512-sample guards, conjugated and fixed training DC removed exactly
% as in the timing driver. Original sample/byte offsets and physical query
% times are logged. Nothing is refitted on frame72. Output: tf_heldout72.
lab=fileparts(mfilename('fullpath'));
addpath(lab,fullfile(lab,'signal_processing'));
inputDir=fullfile(lab,'results','iphone6_cfo_timing_20261026','timing');
outputDir=fullfile(lab,'results','iphone6_cfo_timing_20261026','tf_heldout72');
assert(~isfolder(outputDir)&&~isfile(outputDir),'tf72:Exists','Refusing output overwrite.');
loaded=load(fullfile(inputDir,'model.mat'),'model');model=loaded.model;
frame=72;count=131072;guard=512;n=model.grid_length;
assert(n==2^21,'tf72:Grid','Unexpected canonical grid length.');
assert(model.heldout_frames_zero_based(1)==frame && ...
    ~ismember(frame,model.training_frames_zero_based),'tf72:Split', ...
    'singleTest must be the first heldout frame72, excluded from parameter fitting.');
assert(model.iq_polarity==-1,'tf72:Polarity','This driver reproduces the saved conjugated-IQ convention.');
start=floor(n*1000/1881);u0=start/n;uLast=(start+count-1)/n;
assert(start+count<=n,'tf72:Bounds','Excerpt must stay within the same frame.');
fc=[100e6 160e6];rawCell=cell(1,2);correctedCell=cell(1,2);nativeCell=cell(1,2);
inputMeta=cell(1,2);readInfo=cell(1,2);nativeIdentity=cell(1,2);queryInfo=cell(1,2);
paths=cell(1,2);nativeFirst=zeros(1,2);fsGrid=zeros(1,2);fsNative=zeros(1,2);bytes=zeros(1,2);
for b=1:2
    paths{b}=fullfile(inputDir,sprintf('band_fc%d.mat',fc(b)/1e6));
    header=load(paths{b},'meta');meta=header.meta;inputMeta{b}=meta;
    assert(meta.fc_hz==fc(b) && meta.heldout_frames_zero_based(1)==frame, ...
        'tf72:Band','Unexpected band/frame identity.');
    source=matfile(paths{b});
    rawCell{b}=source.singleTest(start+(1:count),1);
    correctedCell{b}=source.singleTest(start+(1:count),4);
    fsGrid(b)=meta.fs_grid_hz;fsNative(b)=meta.fs_native_hz;
    assert(fsNative(b)==model.fs_native_hz && abs(fsGrid(b)-n/model.canonical_period_seconds)<1e-6, ...
        'tf72:Rates','Band/model rate mismatch.');
    priorPeriod=model.baseline_period_samples;
    correctedPeriod=model.used_period_samples_by_arm_and_band(4,b);
    originalRecord=model.read_records{b,numel(model.training_frames_zero_based)+1};
    originalBlockFirst=originalRecord.first_sample_zero_based;
    rawQueryStart=model.origin_samples+(frame+u0)*priorPeriod;
    rawQueryLast=model.origin_samples+(frame+uLast)*priorPeriod;
    correctedQueryStart=model.origin_samples+(frame+u0)*correctedPeriod;
    correctedQueryLast=model.origin_samples+(frame+uLast)*correctedPeriod;
    % Match analyzeIphonePairTiming's local qRaw then floor operation exactly.
    qRawStart=rawQueryStart-originalBlockFirst;
    nativeFirst(b)=originalBlockFirst+floor(qRawStart);
    assert(nativeFirst(b)>=guard,'tf72:NativeBounds','Insufficient native left guard.');
    [capturePath,identity]=resolveIphoneSweepCapture(fc(b)/1e6);
    previous=model.identities{b};
    assert(identity.bytes==previous.bytes && ...
        string(identity.expected_sha256)==string(previous.expected_sha256), ...
        'tf72:Identity','Resolved capture does not match the timing-run inventory.');
    [nativeWithGuards,record]=readRisIqBlock(capturePath,nativeFirst(b)-guard,count+2*guard);
    dc=complex(model.dc_after_conjugation_real(b),model.dc_after_conjugation_imag(b));
    nativeWithGuards=conj(nativeWithGuards)-single(dc);
    nativeCell{b}=nativeWithGuards(guard+(1:count));
    nativeIdentity{b}=identity;readInfo{b}=record;
    queryInfo{b}=struct('nominal_fc_hz',fc(b),'frame_zero_based',frame, ...
        'canonical_start_index_zero_based',start,'canonical_samples',count, ...
        'canonical_time_since_origin_start_s',(frame+u0)*model.canonical_period_seconds, ...
        'canonical_time_since_origin_end_s',(frame+uLast)*model.canonical_period_seconds, ...
        'canonical_duration_s',count/fsGrid(b),'native_returned_samples',count, ...
        'native_duration_s',count/fsNative(b),'native_first_sample_zero_based',nativeFirst(b), ...
        'native_byte_offset',4*nativeFirst(b),'original_timing_read_first_sample_zero_based',originalBlockFirst, ...
        'native_read_guard_each_side',guard,'raw_query_capture_samples',[rawQueryStart rawQueryLast], ...
        'corrected_query_capture_samples',[correctedQueryStart correctedQueryLast], ...
        'raw_query_capture_time_s',[rawQueryStart rawQueryLast]/fsNative(b), ...
        'corrected_query_capture_time_s',[correctedQueryStart correctedQueryLast]/fsNative(b), ...
        'raw_minus_native_start_fraction_samples',rawQueryStart-nativeFirst(b), ...
        'corrected_minus_raw_start_samples',correctedQueryStart-rawQueryStart, ...
        'corrected_minus_raw_start_ns',1e9*(correctedQueryStart-rawQueryStart)/fsNative(b), ...
        'corrected_minus_raw_end_samples',correctedQueryLast-rawQueryLast, ...
        'fixed_dc_after_conjugation_real',real(dc),'fixed_dc_after_conjugation_imag',imag(dc), ...
        'applied_native_cfo_hz',model.cfo.applied_native_cfo_hz(b));
    item=dir(paths{b});bytes(b)=item.bytes;
    fprintf(['TF heldout72 fc%.0fMHz: %d canonical samples, Fs=%.9fMS/s; ' ...
        '%d native samples, Fs=%.9fMS/s; native original offset=%d; ' ...
        'canonical start=%.9fs after origin; accumulated time shift=%.6fsamples (%.3fns).\n'], ...
        fc(b)/1e6,count,fsGrid(b)/1e6,count,fsNative(b)/1e6,nativeFirst(b), ...
        queryInfo{b}.canonical_time_since_origin_start_s, ...
        queryInfo{b}.corrected_minus_raw_start_samples,queryInfo{b}.corrected_minus_raw_start_ns);
end
metadata=struct;
metadata.nominal_fc_hz=fc;
metadata.native_cell=nativeCell;
metadata.native_fs_hz=fsNative;
metadata.native_start_samples=nativeFirst;
metadata.canonical_start_index_zero_based=[start start];
metadata.source_frame_zero_based=[frame frame];
metadata.raw_description='Saved frame72 singleTest column1: fixed prior-grid guarded sampling, no fitted time/CFO correction';
metadata.corrected_description='Saved frame72 singleTest column4: frozen training CFO then frozen AM-derived time sampling';
metadata.native_description='Re-read contiguous native-rate frame72 IQ; conjugated and saved fixed training DC removed; no interpolation/CFO correction';
metadata.iq_polarity=model.iq_polarity;
metadata.rf_coordinate_convention=model.cfo.baseband_sign_convention;
metadata.input_mat_paths=paths;
metadata.input_mat_bytes=bytes;
metadata.input_band_metadata=inputMeta;
metadata.native_capture_identities=nativeIdentity;
metadata.native_guard_read_records=readInfo;
metadata.physical_query_coordinates=queryInfo;
metadata.timing_model=model;
metadata.selection='Fixed frame72, canonical line1000 region,131072 samples; prior106MHz/q16/display0.75; no TF-based parameter search';
metadata.comparison_scope='Frame72 excluded from the Oct26 fit; this is a processing diagnostic, not a new independent capture or a stitching validity test';
metadata.native_canonical_origin_note='Native first index is floor of the fixed-prior canonical query. Corrected physical queries differ by frozen time mapping; coordinates logged explicitly.';
options=struct('SubbandRfHz',106e6,'Decimation',16,'DisplayNyquistFraction',0.75);
manifest=plotIphonePairTf(rawCell,correctedCell,fsGrid,outputDir,metadata,options);
fid=fopen(fullfile(outputDir,'HELDOUT_CONTEXT.md'),'w','n','UTF-8');
assert(fid>=0,'tf72:Write','Cannot write heldout context.');cleaner=onCleanup(@()fclose(fid));
fprintf(fid,['# Frame72 TF after accumulated timing drift\n\n' ...
    'Frame index72 is zero based and excluded from the Oct26 training fit. ' ...
    'The canonical excerpt starts at index%d, near the line1000 raster coordinate, and has%d samples. ' ...
    'Before/after are saved singleTest columns1/4; no parameter is refitted here.\n\n'],start,count);
for b=1:2
    info=queryInfo{b};
    fprintf(fid,['## fc%.0fMHz\n\n' ...
        '- Canonical Fs: %.12gHz; original native Fs: %.12gHz.\n' ...
        '- Canonical start since frame-origin: %.12gs; duration: %.12gs.\n' ...
        '- Native original first complex-sample index: %.0f (zero based); byte offset: %.0f.\n' ...
        '- Native returned duration: %.12gs, before helper matching-duration truncation.\n' ...
        '- Corrected minus raw starting query: %.9gsamples = %.9gns.\n' ...
        '- Frozen native CFO applied to corrected arm: %.12gHz.\n\n'], ...
        fc(b)/1e6,fsGrid(b),fsNative(b),info.canonical_time_since_origin_start_s, ...
        info.canonical_duration_s,info.native_first_sample_zero_based,info.native_byte_offset, ...
        info.native_duration_s,info.corrected_minus_raw_start_samples, ...
        info.corrected_minus_raw_start_ns,info.applied_native_cfo_hz);
end
fprintf(fid,['Native control is unresampled but conjugated and fixed training DC removed. ' ...
    'Different physical query times are not concealed: exact intervals are in manifest.json. ' ...
    'Amplitude gates are heuristics, and short TF windows do not resolve a sub-kHz CFO directly. ' ...
    'Colors are shared within this frame72 run; cross-run frame0/frame72 image brightness is not automatically calibrated.\n']);
fprintf('Heldout72 toolbox TF complete: %s\n',outputDir);
end
