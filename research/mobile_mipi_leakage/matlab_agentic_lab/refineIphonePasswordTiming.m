function output = refineIphonePasswordTiming()
%REFINEIPHONEPASSWORDTIMING Correct frame drift using only saved frames 2:48.
% The line period and first origin are preserved. Raw capture bytes are read
% again without looping; frames 49:64 are excluded from the period fit.
labRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(labRoot,'signal_processing'));
root = fullfile(labRoot,'results','iphone_recovery_20261023');
previous = fullfile(root,'password_105_P064');
out = fullfile(root,'password_105_P064_refined');
assert(~isfolder(out),'iphone:Exists','Refuse overwrite: %s',out);

saved = load(fullfile(previous,'raster_final.mat'),'device');
d = saved.device;
p = jsondecode(fileread(fullfile(root,'password_diagnostic','diagnostic.json')));
oldFrames = readtable(fullfile(previous,'frame_parameters.csv'));
fitMask = oldFrames.frame>=2 & oldFrames.frame<=48;
assert(nnz(fitMask)==47,'iphone:TrainingFrames','Require every frame from 2 through 48.');
assert(all(isfinite(oldFrames.shift_columns(fitMask))), ...
    'iphone:InvalidTraining','Training shifts must be finite.');
assert(all(abs(oldFrames.shift_columns(fitMask))<24), ...
    'iphone:SaturatedTraining','Do not fit shifts clipped at the old search boundary.');
coefficient = polyfit(double(oldFrames.frame(fitMask)-1), ...
    double(oldFrames.shift_columns(fitMask)),1);
lineSamples = d.fs_hz/d.prior_line_hz;
step = lineSamples/d.raster_columns;
oldPeriod = d.prior_frame_samples;
newPeriod = oldPeriod-coefficient(1)*step;
assert(isfinite(newPeriod) && newPeriod>0,'iphone:BadPeriod','Invalid fitted frame period.');
d.prior_frame_samples = newPeriod;

cfg = mobileBaselineConfig();
cfg.figure_visible = 'off';
cfg.max_frames = 64;
cfg.checkpoints = [1 8 16 32 64];
cfg.maximum_alignment_columns = 96;
first = oldFrames.start_sample(oldFrames.frame==1);
assert(isscalar(first),'iphone:FirstFrame','Require exactly one first-frame record.');
cfg.first_sample = first-4-d.origin_columns*step;
residual = oldFrames.shift_columns(fitMask)- ...
    polyval(coefficient,double(oldFrames.frame(fitMask)-1));
refinement = struct('status','configured','source',string(p.source), ...
    'prior_output',previous,'output',out,'training_frames',[1 48], ...
    'period_fit_frames',[2 48],'evaluation_frames',[49 64], ...
    'fit_method','polyfit(frame-1, shift_columns, 1), saved frames 2:48 only', ...
    'shift_slope_columns_per_frame',coefficient(1), ...
    'shift_intercept_columns',coefficient(2), ...
    'fit_residual_rms_columns',sqrt(mean(residual.^2)), ...
    'old_frame_period_samples',oldPeriod,'new_frame_period_samples',newPeriod, ...
    'period_change_samples',newPeriod-oldPeriod,'line_period_samples',lineSamples, ...
    'samples_per_output_column',step,'first_sample',cfg.first_sample, ...
    'origin_columns',d.origin_columns,'old_alignment_limit_columns',24, ...
    'new_alignment_limit_columns',96, ...
    'old_training_alignment',alignmentSummary(oldFrames,[1 48],24), ...
    'old_evaluation_alignment',alignmentSummary(oldFrames,[49 64],24), ...
    'caveat',['Only the frame-period slope excludes frames 49:64. Every frame still aligns ' ...
    'to the common frame-1 profile; phase fitting and aggregate odd/even metrics are not ' ...
    'independent held-out image validation. The alignment window also changes from 24 to ' ...
    '96 columns, so this run does not isolate the period correction alone. Stable clutter ' ...
    'may determine the timing. No raw-file playback loop or new independent observations are created.']);
mkdir(out);
writeJsonFile(fullfile(out,'refinement.json'),refinement);
writeJsonFile(fullfile(out,'config.json'),struct('device',d,'config',cfg));
fprintf('Password timing: %.9f -> %.9f samples/frame; slope %.9f columns/frame\n', ...
    oldPeriod,newPeriod,coefficient(1));
result = compareRasterAverages(string(p.source),d,cfg,out,fullfile(out,'notes.jsonl'));
writeJsonFile(fullfile(out,'metrics.json'),result);
newFrames = readtable(fullfile(out,'frame_parameters.csv'));
refinement.status = 'complete';
refinement.new_training_alignment = alignmentSummary(newFrames,[1 48],96);
refinement.new_evaluation_alignment = alignmentSummary(newFrames,[49 64],96);
refinement.frames_processed = result.frames;
writeJsonFile(fullfile(out,'refinement.json'),refinement);
output = struct('reconstruction',result,'refinement',refinement);
end

function summary = alignmentSummary(records,range,limit)
mask = records.frame>=range(1) & records.frame<=range(2);
shift = records.shift_columns(mask);
summary = struct('frame_range',range,'count',nnz(mask), ...
    'minimum_shift_columns',min(shift),'maximum_shift_columns',max(shift), ...
    'saturated_frames',records.frame(mask & abs(records.shift_columns)>=limit-1e-9).', ...
    'mean_profile_correlation',mean(records.profile_correlation(mask)), ...
    'minimum_profile_correlation',min(records.profile_correlation(mask)));
end
